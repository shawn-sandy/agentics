#!/usr/bin/env node
/**
 * retrofit-responsive-plans.mjs — inject the versioned responsive-CSS
 * <style> block into shipped HTML plans that lack it (Step 1 of
 * docs/plans/retrofit-responsive-plan-css.html). Third injector in the
 * backfill family, after scripts/backfill-plan-digests.mjs (2.3.0) and
 * scripts/backfill-save-pdf.mjs (2.4.0).
 *
 * Contract:
 *   - The block is wrapped as <style id="plan-responsive-fix"
 *     data-version="1"> and inserted immediately before </head>. The
 *     id + data-version pair is the idempotency key: current version →
 *     skip; older version → replace the whole block (no duplication);
 *     missing → inject.
 *   - HEAD-SCOPED: detection AND injection operate only on the region
 *     before the first </head> (case-insensitive). A whole-file match
 *     would falsely skip plans whose <body> digest happens to quote the
 *     literal <style id="plan-responsive-fix" data-version="1"> string
 *     (e.g. docs/plans/retrofit-responsive-plan-css.html). Output is
 *     therefore byte-identical from <body onward — markup, ARIA, and
 *     semantics can never change.
 *   - Deterministic: the injected/replaced bytes are identical on every
 *     run (STYLE_BLOCK followed by a single newline before </head>), so
 *     a second run is a no-op with an empty git diff.
 *   - docs/plans/index.html is always excluded (regenerated by
 *     docs/plans/build-index.sh via the rebuild hook).
 *   - Files with no </head> are reported and left untouched — never
 *     half-written.
 *
 * Usage: node scripts/retrofit-responsive-plans.mjs [--check] [--dry-run] [--dir <path>] [--include-archive]
 *   --check            never write; exit 1 listing every file that would be
 *                      injected or replaced, exit 0 when the corpus is current.
 *                      'error' files (no </head>) are reported but do NOT by
 *                      themselves cause a non-zero exit (they are unfixable,
 *                      not drift).
 *   --dry-run          print would-inject / would-replace / would-skip actions
 *                      without writing any file.
 *   --dir <path>       plans directory (default: docs/plans resolved from the
 *                      script location, not cwd).
 *   --include-archive  ALSO process <dir>/archive/ recursively. Off by default —
 *                      the default run is non-recursive, so archive/ is skipped.
 */

import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, basename } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const DEFAULT_DIR = join(fileURLToPath(new URL('..', import.meta.url)), 'docs', 'plans');

export const CURRENT_VERSION = 1;

export const STYLE_BLOCK = `<style id="plan-responsive-fix" data-version="1">
/* plan-responsive-fix v1 — injected by scripts/retrofit-responsive-plans.mjs */
body { overflow-wrap: anywhere; }
main, nav, aside { min-width: 0; }
.layout > *, .wrap > *, .compare-grid > * { min-width: 0; }
pre { white-space: pre-wrap; max-width: 100%; }
table { max-width: 100%; }
img, video { max-width: 100%; height: auto; }
@media (max-width: 600px) { .compare-grid { grid-template-columns: 1fr; } }
</style>`;

// Matches an existing injected block, capturing its data-version. Scoped to
// the <head> region by the caller, never run against the whole file.
const EXISTING_BLOCK_RE =
  /<style id="plan-responsive-fix" data-version="(\d+)">[\s\S]*?<\/style>/i;

/**
 * Decide what to do with a single HTML document. Pure — no I/O. Returns one of:
 *   { action: 'inject',  html }   — no block in <head>; STYLE_BLOCK + '\n'
 *                                    inserted immediately before </head>.
 *   { action: 'replace', html }   — older data-version in <head>; the whole
 *                                    block swapped for STYLE_BLOCK, no dupes.
 *   { action: 'skip', reason }    — <head> already at the current version;
 *                                    html is returned unchanged (byte-identical).
 *   { action: 'error', reason }   — no </head> found; never written.
 */
export function inject(html) {
  const headEnd = html.search(/<\/head>/i);
  if (headEnd === -1) return { action: 'error', reason: 'no </head> found' };

  const head = html.slice(0, headEnd);
  const rest = html.slice(headEnd); // begins at "</head>" — preserved verbatim

  const match = head.match(EXISTING_BLOCK_RE);
  if (match) {
    const version = Number(match[1]);
    if (version >= CURRENT_VERSION) {
      return { action: 'skip', reason: `already at v${version}` };
    }
    const newHead = head.replace(EXISTING_BLOCK_RE, STYLE_BLOCK);
    return { action: 'replace', html: newHead + rest };
  }

  // No block in <head>: insert STYLE_BLOCK + a single newline before </head>.
  return { action: 'inject', html: head + STYLE_BLOCK + '\n' + rest };
}

/** List *.html files in a directory (non-recursive), excluding index.html. */
function listPlanFiles(dir) {
  return readdirSync(dir, { withFileTypes: true })
    .filter((e) => e.isFile() && e.name.endsWith('.html') && e.name !== 'index.html')
    .map((e) => join(dir, e.name))
    .sort();
}

/** Recursively list *.html files under a directory, excluding index.html. */
function listPlanFilesRecursive(dir) {
  const out = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) {
      out.push(...listPlanFilesRecursive(path));
    } else if (entry.isFile() && entry.name.endsWith('.html') && entry.name !== 'index.html') {
      out.push(path);
    }
  }
  return out.sort();
}

function main() {
  const args = process.argv.slice(2);
  const check = args.includes('--check');
  const dryRun = args.includes('--dry-run');
  const includeArchive = args.includes('--include-archive');
  const dirIdx = args.indexOf('--dir');
  const dir = dirIdx !== -1 ? args[dirIdx + 1] : DEFAULT_DIR;

  // Default run is non-recursive (archive/ skipped). --include-archive also
  // walks <dir>/archive/ recursively.
  const files = listPlanFiles(dir);
  if (includeArchive) {
    let archiveDir;
    try {
      archiveDir = join(dir, 'archive');
      readdirSync(archiveDir);
      files.push(...listPlanFilesRecursive(archiveDir));
    } catch {
      // No archive/ directory — nothing extra to process.
    }
  }

  let injected = 0, replaced = 0, skipped = 0;
  const errors = [];
  const drift = []; // files --check would flag (inject or replace)

  for (const path of files) {
    const html = readFileSync(path, 'utf8');
    const result = inject(html);
    const rel = basename(path);

    if (result.action === 'error') {
      errors.push(`${rel} — ${result.reason}`);
      continue;
    }
    if (result.action === 'skip') {
      skipped += 1;
      if (dryRun) console.log(`[dry-run] would-skip ${rel} — ${result.reason}`);
      continue;
    }

    // inject | replace
    drift.push(`${rel} — would-${result.action}`);
    if (result.action === 'inject') injected += 1;
    else replaced += 1;

    if (check) continue; // --check never writes
    if (dryRun) {
      console.log(`[dry-run] would-${result.action} ${rel}`);
      continue;
    }
    writeFileSync(path, result.html);
    console.log(`${result.action} ${rel}`);
  }

  if (check) {
    console.log(
      `${drift.length} file(s) need the responsive block ` +
      `(${injected} inject, ${replaced} replace), ${skipped} current, ` +
      `${errors.length} unfixable (no </head>)`,
    );
    for (const d of drift) console.log(`  DRIFT ${d}`);
    for (const e of errors) console.log(`  ERROR ${e}`);
    process.exit(drift.length > 0 ? 1 : 0);
  }

  console.log(
    `\n${injected} injected, ${replaced} replaced, ${skipped} skipped, ` +
    `${errors.length} errored${dryRun ? ' (dry-run — nothing written)' : ''}`,
  );
  for (const e of errors) console.log(`  ERROR ${e}`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main();
}
